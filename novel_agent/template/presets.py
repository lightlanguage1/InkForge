def install_presets(db: "TemplateDB") -> None:
    """将 presets.py 中定义的预设写入 DB，已存在则跳过。"""
    for preset in STYLE_PRESETS:
        db.insert_if_not_exists(
            preset["id"], preset["name"],
            preset.get("description", ""),
            preset.get("prompt_snippet", ""),
            "style", is_preset=True,
        )
    for preset in CRAFT_PRESETS:
        db.insert_if_not_exists(
            preset["id"], preset["name"],
            preset.get("description", ""),
            preset.get("prompt_snippet", ""),
            "craft", is_preset=True,
        )
